/**
 * Pre-build script: bundles content/ (posts, authors, doa) into generated
 * modules under lib/generated/content/ (git-ignored).
 *
 * Why: Cloudflare Workers have neither a runtime filesystem nor dynamic code
 * evaluation (`new Function`, which next-mdx-remote needs). So blog posts are
 * compiled to React modules at build time and loaded through a static registry
 * of dynamic imports; frontmatter lives in JSON. Works the same on Vercel.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from "fs";
import { join } from "path";
import matter from "gray-matter";
import readingTime from "reading-time";
import { compile } from "@mdx-js/mdx";
import remarkGfm from "remark-gfm";
import rehypeSlug from "rehype-slug";
import rehypeAutolinkHeadings from "rehype-autolink-headings";

const ROOT = process.cwd();
const OUT = join(ROOT, "lib/generated/content");

function readDir(dir: string): Record<string, string> {
  const full = join(ROOT, dir);
  const out: Record<string, string> = {};
  if (!existsSync(full)) return out;
  for (const file of readdirSync(full).sort()) {
    if (!/\.mdx?$/.test(file)) continue;
    out[file.replace(/\.mdx?$/, "")] = readFileSync(join(full, file), "utf8");
  }
  return out;
}

async function main() {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(join(OUT, "mdx"), { recursive: true });

  // Posts: frontmatter + compiled MDX modules
  const posts = readDir("content/posts");
  const postMeta: Record<string, unknown> = {};
  const lines: string[] = [];
  let index = 0;
  for (const [slug, source] of Object.entries(posts)) {
    const fileName = `m${index++}.js`;
    const { content, data } = matter(source);
    postMeta[slug] = {
      data,
      readingTimeList: readingTime(source).text,
      readingTimePost: readingTime(content).text,
    };
    const compiled = await compile(content, {
      outputFormat: "program",
      development: false,
      remarkPlugins: [remarkGfm],
      rehypePlugins: [rehypeSlug, rehypeAutolinkHeadings as any],
    });
    writeFileSync(join(OUT, "mdx", fileName), String(compiled));
    lines.push(`  ${JSON.stringify(slug)}: () => import("./mdx/${fileName}"),`);
  }
  writeFileSync(join(OUT, "posts.json"), JSON.stringify(postMeta));
  writeFileSync(
    join(OUT, "mdx-registry.ts"),
    `// AUTO-GENERATED by scripts/generate-content-bundle.ts - do not edit\n/* eslint-disable */\n// @ts-nocheck\nimport type { ComponentType } from "react";\n\nexport type MdxLoader = () => Promise<{ default: ComponentType<any> }>;\n\nexport const postsMdx: Record<string, MdxLoader> = {\n${lines.join("\n")}\n};\n`
  );

  // Authors: frontmatter + raw body (rendered as plain text, as before)
  const authors: Record<string, unknown> = {};
  for (const [slug, source] of Object.entries(readDir("content/authors"))) {
    const { data, content } = matter(source);
    authors[slug] = { data, content };
  }
  writeFileSync(join(OUT, "authors.json"), JSON.stringify(authors));

  // Doa: content/doa/sources/<group>/<file>.mdx
  const doaRoot = join(ROOT, "content/doa/sources");
  const doa: { groupSlug: string; fileName: string; data: unknown; content: string }[] = [];
  if (existsSync(doaRoot)) {
    for (const group of readdirSync(doaRoot, { withFileTypes: true })) {
      if (!group.isDirectory()) continue;
      for (const [fileName, source] of Object.entries(readDir(`content/doa/sources/${group.name}`))) {
        const { data, content } = matter(source);
        doa.push({ groupSlug: group.name, fileName, data, content });
      }
    }
  }
  writeFileSync(join(OUT, "doa.json"), JSON.stringify(doa));

  console.log(
    `content bundle: ${Object.keys(postMeta).length} posts, ${Object.keys(authors).length} authors, ${doa.length} doa`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
